package main

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"

	"github.com/Oudwins/zog/internal/codegen"
)

const defaultOutput = "metadata_generated.go"

func main() {
	root := flag.String("root", ".", "path to the zog package")
	out := flag.String("out", defaultOutput, "output file path")
	flag.Parse()

	generated, err := generate(*root)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, generated, 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(root string) ([]byte, error) {
	schemas, err := codegen.ZogSchemas(root)
	if err != nil {
		return nil, err
	}

	var out bytes.Buffer
	out.WriteString("// Code generated by go generate; DO NOT EDIT.\n\n")
	out.WriteString("package zog\n\n")
	out.WriteString("import \"github.com/Oudwins/zog/zconst\"\n\n")
	for _, schema := range schemas {
		fmt.Fprintf(&out, `func (s *%[1]s) Meta(k zconst.ZogMetaKey, v any) *%[1]s {
	GlobalMetaRegistry.Set(s, k, v)
	return s
}

func (s *%[1]s) MetaFunc(f func() SchemaMetadata) *%[1]s {
	m := f()
	GlobalMetaRegistry.SetCopy(s, m)
	return s
}

func (s *%[1]s) Registry(r ZogMetaRegistry, k zconst.ZogMetaKey, v any) *%[1]s {
	r.Set(s, k, v)
	return s
}

func (s *%[1]s) RegistryFunc(f func() (ZogMetaRegistry, SchemaMetadata)) *%[1]s {
	r, m := f()
	r.SetCopy(s, m)
	return s
}

`, schema)
	}

	generated, err := format.Source(out.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated metadata: %w", err)
	}
	return generated, nil
}
